from deepeval.metrics import GEval
from deepeval.test_case import LLMTestCaseParams

from eval.metrics.judge_model import judge_llm

#SymbolExplanation
se_metric = GEval(
    name="symbol_explanantion",
    criteria="당신은 질문 내의 기호에 대한 설명이 대답에 잘 포함되어 있는지 판단하는 심판관입니다." \
    "당신이 받을 질문은 'a가 b에서 사용됐습니다. 현재 페이지: c. 기호에 대해서 설명해주세요.'라는 형태의 질문을 봅니다." \
    "여기서 a, b가 '$' 기호 사이에 LaTeX/KaTeX 문법으로 표현되어 있는데," \
    "이 a에 해당하는 '$' 기호 사이의 LaTeX/KaTeX 문법에 대한 설명이" \
    "b에 해당하는 '$' 기호 사이의 LaTeX/KaTeX 문법에서 무슨 역할을 하는지" \
    "그리고 c에서 어떤 역할을 하는지에 대해 상세하게 설명되었는지 0~1의 점수로 판단해주세요." \
    "b와 연관지어 설명한다는 것은, b 식에 함께 등장하는 다른 기호나 구조와의 관계를 언급하는 것을 말합니다." \
    "기호 자체의 일반적인 정의만 서술하는 것은 b와 연관지은 것으로 보지 않습니다." \
    "c와 연관지어 설명한다는 것은, 해당 정의/정리 안에서 그 기호가 왜 필요한지 또는 무엇을 뜻하는지를 언급하는 것을 말합니다." \
    "페이지 제목만 언급하는 것은 연관지은 것으로 보지 않습니다." \
    "" \
    "평가하지 마세요:" \
    "- 답변의 유용성" \
    "- 답변의 문장 품질" \
    "- 답변의 Faithfulness 등 참조된 문서를 검증하는 평가" \
    "" \
    "기준:" \
    "- 1.0: 질문 내의 a에 해당하는 문법을 주어로 한 문장이 대답에 존재하여 b와 c 둘 다와 연관지어 설명합니다." \
    "- 0.75: 질문 내의 a에 해당하는 문법을 주어로 하는 문장이 존재하고, c와만 연관지어 설명하고, b의 설명이 누락되어 있습니다." \
    "- 0.5: 질문 내의 a에 해당하는 문법을 주어로 하는 문장이 존재하나, b와만 연관지어 설명하거나, 기호의 일반적인 정의만 서술합니다. 기호의 일반적 정의를 정확히 서술한 경우가 여기에 해당하며, 설명이 정확하다면 0.25로 내리지 마세요. 0.25는 기호를 언급만 하고 설명이 전혀 없는 경우입니다." \
    "- 0.25: 질문 내의 a에 해당하는 문법이 대답에 포함되어 있지만 어떠한 설명도 하지 않습니다." \
    "- 0.0: 질문 내의 a에 해당하는 문법이 대답에 포함되어 있지 않습니다." \
    "" \
    "주의:" \
    "- 질문 내의 a에 해당하는 기호가 b에 해당하는 문법이나 c에 큰 연관이 없다고 말하면서 이에 대한 명확한 근거를 제시한 경우에 상세하게 설명하는 것으로 생각합니다." \
    "- b에 해당하는 문법이나 c에 대한 설명을 하고, 추가 설명을 하는 것은 감점 요소가 아닙니다." \
    "- b에 해당하는 문법이나 c에 대한 설명이 들어가는 순서가 틀린 것은 감점 요소가 아닙니다." \
    "- 평가 이유를 작성할 때 LaTeX 명령어(\\frac, \\sup 등)를 그대로 쓰지 말고 기호 이름을 한글이나 영어 단어로 풀어 쓰세요.",
    evaluation_params=[
        LLMTestCaseParams.INPUT,
        LLMTestCaseParams.ACTUAL_OUTPUT
    ],
    model=judge_llm
)

#AnswerReference
ar_metric = GEval(
    name="answer_reference",
    criteria="당신은 답변 품질을 평가하는 채점자입니다." \
    "아래의 기대 답변과 모델을 통한 답변을 비교하고," \
    "응답이 기대 답변과 의미가 일치하는지 핵심 내용의 여부를 통해 0~1의 점수로 판단해주세요." \
    "" \
    "평가하지 마세요:" \
    "- 답변의 유용성" \
    "- 답변의 문장 품질" \
    "- 답변의 Faithfulness 등 참조된 문서를 검증하는 평가" \
    "- 필요한 기호가 들어갔는지 여부" \
    "- 기대 답변의 구조와 유사한가" \
    "- 기대 답변에 없는 추가 내용의 사실 여부" \
    "" \
    "기준:" \
    "- 1.0: 기대 답변 안에 있는 모든 핵심 내용들이 모델을 통한 답변 안에 있습니다." \
    "- 0.75: 기대 답변 안에 있는 대부분의 핵심 내용들이 모델을 통한 답변 안에 있고, 소수의 핵심 내용들이 누락되었더라도 모델을 통한 답변 안에 틀린 말은 없습니다." \
    "- 0.5: 기대 답변 안에 있는 절반 정도의 핵심 내용들이 모델을 통한 답변 안에 있거나, 절반 이상의 핵심 내용이 담겼더라도 부정확한 말이 들어 있습니다." \
    "- 0.25: 기대 답변 안에 있는 소수의 핵심 내용들이 모델을 통한 답변 안에 있고, 대부분의 핵심 내용들이 누락되었습니다." \
    "- 0.0: 기대 답변 안에 어떠한 핵심 내용도 모델을 통한 답변 안에 있지 않고 무관합니다." \
    "" \
    "주의:" \
    "- 단어가 다르더라도 수학적으로 동치인 대상이나 문장을 설명한다면 의미가 일치한다고 보지만, 수학적으로 동치더라도 전제 조건, 정의역이 빠지면 일치한다고 보지 않습니다." \
    "- 기대 답변의 순서와 모델을 통한 답변의 의미가 일치하는 순서가 같은지 중요하지 않습니다." \
    "- 기대 답변의 핵심 내용을 모두 담았다면, 그 외 추가 설명의 양이나 정오와 무관하게 재현 기준으로 만점을 줄 수 있습니다." \
    "평가 이유를 작성할 때 LaTeX 명령어(\\frac, \\sup 등)를 그대로 쓰지 말고 기호 이름을 한글이나 영어 단어로 풀어 쓰세요.",
    evaluation_params=[
        LLMTestCaseParams.INPUT,
        LLMTestCaseParams.ACTUAL_OUTPUT,
        LLMTestCaseParams.EXPECTED_OUTPUT
    ],
    model=judge_llm
)


