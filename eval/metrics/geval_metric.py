ne_metric = GEval(
    name="natural_explanation",
    criteria="이 답변은 구어체로 작성된 개인 학습 노트를 참조해 생성되었습니다. 답변에 노트의 날것 구어체(ㅋㅋㅋ, ~함, ~했음, 반말 등)가 그대로 남아있지 않고 정돈된 톤앤매너(~해요/~합니다)로 다듬어졌는지 평가해주세요." \
    "평가하지 마세요:" \
    "- 답변의 정확성" \
    "- 답변의 유용함" \
    "- 답변의 충실성" \
    "- 답변의 학술적 사실 여부" \
    "- 답변의 길이" \
    "- 답변의 유창함" \
    "" \
    "기준:" \
    "- 1.0: 매우 자연스럽고 명쾌한 친절체(~해요, ~합니다). 검색 문서의 날것(Raw) 구어체나 비격식체가 완전히 정돈되어 전문 튜터처럼 설명합니다" \
    "- 0.75: 전체적으로 친절한 톤이지만, 검색 문서의 비격식 문장/단어가 한두 군데 어색하게 남아있습니다." \
    "- 0.5: 답변 안에 절반 정도 검색 문서의 비격식 문장/단어가 남아있습니다. 절반이 한 두 군데 정도라면 0.75점을 먼저 적용합니다." \
    "- 0.25: 반말, 메신저 말투('~임', '~함', 'ㅋㅋㅋ' 등), 혹은 원문의 사담이 그대로 답변에 노출됩니다." \
    "- 0.0: 전체적으로 반말/비격식체입니다." \
    "" \
    "주의:" \
    "- 문맥상 자연스러운 가벼운 추임새(예: '자, 생각해보자...', '정리해 볼게요!')는 감점 대상이 아닙니다." \
    "평가 이유를 작성할 때 LaTeX 명령어(\\frac, \\sup 등)를 그대로 쓰지 말고 기호 이름을 한글이나 영어 단어로 풀어 쓰세요.",
    evaluation_params=[
        LLMTestCaseParams.INPUT,
        LLMTestCaseParams.ACTUAL_OUTPUT,
    ],
    model=judge_llm,\
)